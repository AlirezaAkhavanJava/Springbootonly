CREATE TABLE account_user
(
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         varchar(255) NOT NULL,
    password_hash varchar(255) NOT NULL,
    username      varchar(255) NOT NULL,
    created_at    timestamptz(6) NOT NULL,
    enabled       boolean      NOT NULL,
    locked        boolean      NOT NULL,
    role          varchar(255) NOT NULL CHECK (role IN ('ADMIN', 'USER')),
    user_role     varchar(255) NOT NULL CHECK (user_role IN ('ADMIN', 'USER')),
    CONSTRAINT uk_account_user_email UNIQUE (email),
    CONSTRAINT uk_account_user_username UNIQUE (username)
);

CREATE TABLE account_orders
(
    id               uuid PRIMARY KEY,
    account_owner_id bigint NOT NULL,
    CONSTRAINT fk_order_account_owner
        FOREIGN KEY (account_owner_id) REFERENCES account_user (id)
);